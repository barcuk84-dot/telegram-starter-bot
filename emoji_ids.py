"""Анимированные (кастомные) эмодзи Telegram на кнопках.

Как заполнить:
1. Включи на аккаунте владельца бота Telegram Premium (иначе Telegram не покажет их на кнопках).
2. Запусти бота, из своего админ-аккаунта отправь боту сообщение с нужными
   анимированными эмодзи. Бот ответит их ID и готовыми строками для этого файла.
3. Вставь ID ниже вместо пустых кавычек и перезапусти бота.

Пустой ID = у этой кнопки остаётся обычный эмодзи. Ключ — эмодзи, который стоит
в начале текста кнопки в main.py: он заменится на анимированный.
"""

EMOJI_IDS = {
    "🔍": "",   # Поиск
    "⭐": "",   # Оценить / оплата Stars
    "⚖️": "",   # Сравнение
    "📡": "",   # Трекер
    "❤️": "",   # Избранное
    "👤": "",   # Профиль
    "💎": "",   # Тарифы / Premium
    "ℹ️": "",   # Помощь
    "⬅️": "",   # Назад / В меню
    "🗃": "",   # Поиск в базе
    "🤖": "",   # Автопоиск
    "🎟": "",   # Пакеты попыток
    "💵": "",   # Оплата USDT
}

_FE0F = "\ufe0f"


def split_icon(text: str):
    """Если текст кнопки начинается с эмодзи, у которого задан ID, возвращает (текст_без_эмодзи, id).
    Иначе (text, None)."""
    for emoji, emoji_id in EMOJI_IDS.items():
        if not emoji_id:
            continue
        key = emoji.replace(_FE0F, "")
        # посимвольное сравнение с пропуском селекторов вариации
        pos, k = 0, 0
        while pos < len(text) and k < len(key):
            if text[pos] == _FE0F:
                pos += 1
                continue
            if text[pos] != key[k]:
                break
            pos += 1
            k += 1
        else:
            if k == len(key):
                while pos < len(text) and text[pos] == _FE0F:
                    pos += 1
                return text[pos:].lstrip(), emoji_id
    return text, None
